#!/usr/bin/env python
"""`make eval`: runs the simulator against a fresh demo database and prints
honest, measured numbers — not claims. Requires the gateway to already be
running (`make dev` in another terminal).

Reports:
  - detection: how many of the bot accounts got stopped (decoy or collective
    immunity block), and how many of THEIR OWN requests it took each time
  - false positives: how often legitimate accounts (especially Dev CI) were
    punished (any outcome other than "answered")
  - latency: p50/p95 per pipeline step, in milliseconds
  - Model DNA: trap matches and binomial p-value for the clone vs. the clean
    upstream model

All traffic here is synthetic, generated by this script in this run. These
numbers describe THIS demo-scale run, not a general benchmark.
"""
from __future__ import annotations

import json
import math
import sys

sys.path.insert(0, ".")

from app.db import connection  # noqa: E402
from app.demo_actions import (  # noqa: E402
    reset_demo,
    run_scan,
    send_client,
    send_dev_ci,
    send_hacker,
)
from app.demo_actions import send_bot_burst  # noqa: E402

LEGIT_LABELS = ["client1", "client2", "dev-ci"]
STOPPED_OUTCOMES = ("decoy", "immunity_blocked")


def percentile(values: list[float], p: float) -> float | None:
    if not values:
        return None
    s = sorted(values)
    k = (len(s) - 1) * (p / 100)
    f, c = math.floor(k), math.ceil(k)
    if f == c:
        return s[int(k)]
    return s[f] + (s[c] - s[f]) * (k - f)


def bot_detection_report() -> dict:
    with connection() as conn:
        rows = conn.execute(
            """
            SELECT a.label, r.outcome, r.created_at
            FROM requests r JOIN accounts a ON r.account_id = a.account_id
            WHERE a.label LIKE 'bot%'
            ORDER BY a.label, r.created_at
            """
        ).fetchall()

    per_bot: dict[str, list[str]] = {}
    for row in rows:
        per_bot.setdefault(row["label"], []).append(row["outcome"])

    detected = {}
    for label, outcomes in per_bot.items():
        for i, outcome in enumerate(outcomes, start=1):
            if outcome in STOPPED_OUTCOMES:
                detected[label] = {"requests_to_catch": i, "outcome": outcome}
                break
        else:
            detected[label] = {"requests_to_catch": None, "outcome": None}

    total_bots = len(per_bot)
    caught = sum(1 for v in detected.values() if v["requests_to_catch"] is not None)
    return {
        "total_bot_accounts": total_bots,
        "caught": caught,
        "detection_rate": round(caught / total_bots, 3) if total_bots else None,
        "per_bot": detected,
        "note": "Bots are sent in strict round-robin order, so they tend to cross the decoy "
        "threshold within the same request in lockstep. Typically only ONE bot actually reaches "
        "outcome='decoy' (Puaro's own confirmation); the rest show outcome='immunity_blocked' — "
        "they were stopped instantly by collective immunity the moment the first one was confirmed, "
        "even within the same tenant.",
    }


def false_positive_report() -> dict:
    with connection() as conn:
        rows = conn.execute(
            """
            SELECT a.label, r.outcome
            FROM requests r JOIN accounts a ON r.account_id = a.account_id
            WHERE a.label IN ({})
            """.format(",".join("?" for _ in LEGIT_LABELS)),
            LEGIT_LABELS,
        ).fetchall()

    per_label: dict[str, dict] = {label: {"total": 0, "punished": 0} for label in LEGIT_LABELS}
    for row in rows:
        stats = per_label[row["label"]]
        stats["total"] += 1
        if row["outcome"] != "answered":
            stats["punished"] += 1

    for label, stats in per_label.items():
        stats["false_positive_rate"] = round(stats["punished"] / stats["total"], 3) if stats["total"] else None

    return per_label


def latency_report() -> dict:
    with connection() as conn:
        rows = conn.execute(
            "SELECT outcome, t_auth_us, t_immunity_us, t_firewall_us, t_signals_us, t_policy_us, t_model_us, t_total_us "
            "FROM requests"
        ).fetchall()

    buckets: dict[str, list[float]] = {
        "auth": [], "immunity": [], "firewall": [], "signals": [], "policy": [], "model": [], "total": [],
    }
    for row in rows:
        buckets["auth"].append(row["t_auth_us"])
        buckets["immunity"].append(row["t_immunity_us"])
        buckets["total"].append(row["t_total_us"])
        if row["outcome"] != "immunity_blocked":
            buckets["firewall"].append(row["t_firewall_us"])
        if row["outcome"] not in ("firewall_blocked", "immunity_blocked"):
            buckets["signals"].append(row["t_signals_us"])
            buckets["policy"].append(row["t_policy_us"])
        if row["outcome"] not in ("firewall_blocked", "immunity_blocked", "decoy"):
            buckets["model"].append(row["t_model_us"])

    report = {}
    for step, values in buckets.items():
        p50 = percentile(values, 50)
        p95 = percentile(values, 95)
        report[step] = {
            "n": len(values),
            "p50_ms": round(p50 / 1000, 3) if p50 is not None else None,
            "p95_ms": round(p95 / 1000, 3) if p95 is not None else None,
        }
    return report


def main() -> None:
    print("Resetting demo state...")
    reset_demo()

    print("Sending legitimate traffic (Alice, Bob, Dev CI)...")
    send_client(6)
    send_dev_ci(20)

    print("Sending distillation bot swarm (8 accounts, shared origin)...")
    bot_results = []
    for _ in range(20):
        batch = send_bot_burst(8, start_at=len(bot_results) + 1)
        bot_results.extend(batch)
        with connection() as conn:
            stopped = conn.execute(
                "SELECT COUNT(DISTINCT a.label) FROM requests r JOIN accounts a ON r.account_id = a.account_id "
                "WHERE a.label LIKE 'bot%' AND r.outcome IN ('decoy', 'immunity_blocked')"
            ).fetchone()[0]
        if stopped >= 8:
            break

    print("Sending jailbreak attempts...")
    send_hacker(4)

    print("Running Model DNA verifier...\n")
    scan = run_scan()

    report = {
        "detection": bot_detection_report(),
        "false_positives": false_positive_report(),
        "latency_ms": latency_report(),
        "model_dna": scan,
        "note": "All traffic is synthetic, generated by this script in this run. "
        "These numbers describe this demo-scale run, not a general benchmark.",
    }
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
