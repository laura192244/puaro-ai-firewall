#!/usr/bin/env python
"""Plays the full pitch demo end to end: client -> bot -> hacker -> scan
suspect model -> attack Customer B. Requires the gateway to already be
running (`make dev` or `uvicorn app.main:app`) in another terminal."""
from __future__ import annotations

import sys

sys.path.insert(0, ".")

from app.demo_actions import run_full_demo  # noqa: E402


def main() -> None:
    print("=== Puaro demo: client -> bot -> hacker -> scan suspect model -> attack Customer B ===\n")
    result = run_full_demo()

    print(f"1) Legit clients sent: {len(result['clients'])}")
    print(f"2) Dev CI requests sent: {len(result['dev_ci'])} "
          f"(punished: {sum(1 for r in result['dev_ci'] if r['outcome'] not in ('answered', None))})")
    print(f"3) Bot requests sent: {len(result['bots'])} "
          f"(reached decoy tier: {result['bots_reached_decoy']})")
    print(f"4) Hacker requests sent: {len(result['hackers'])} "
          f"(blocked: {sum(1 for r in result['hackers'] if r['status_code'] == 400)})")

    scan = result["scan"]
    print("\n5) Model DNA verifier:")
    print(f"   clone stand-in : {scan['clone']['matches']}/{scan['clone']['total']} trap matches, "
          f"p={scan['clone']['p_value']}")
    print(f"   clean upstream : {scan['clean']['matches']}/{scan['clean']['total']} trap matches, "
          f"p={scan['clean']['p_value']}")

    attack = result["attack_customer_b"]
    legit_b = result["customer_b_legit_unaffected"]
    print("\n6) Attack Customer B:")
    print(f"   attacker (same origin as custA bots) -> HTTP {attack['status_code']} "
          f"({'BLOCKED by collective immunity' if attack['status_code'] == 403 else 'not blocked'})")
    print(f"   unrelated Customer B user            -> HTTP {legit_b['status_code']} "
          f"({'unaffected' if legit_b['status_code'] == 200 else 'unexpectedly affected'})")

    print("\nAll traffic in this demo is synthetic, generated by this script.")


if __name__ == "__main__":
    main()
